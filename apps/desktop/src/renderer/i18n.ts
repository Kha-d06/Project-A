export const DICTS: Record<Lang, Dict> = { en, ar };
export function resolve(setting: string, systemLocale: string): Lang {
  if (setting === "en" || setting === "ar") return setting;
  return systemLocale.toLowerCase().startsWith("ar") ? "ar" : "en";
}

