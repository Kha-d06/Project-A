import { NextResponse, type NextRequest } from "next/server";

/** Issues a per-request nonce so only scripts rendered by the app itself can run. */
export function proxy(request: NextRequest) {
  const nonce = Buffer.from(crypto.randomUUID()).toString("base64");
  const isDev = process.env.NODE_ENV === "development";

  const policy = [
    "default-src 'self'",
    `script-src 'self' 'nonce-${nonce}' 'strict-dynamic'${isDev ? " 'unsafe-eval'" : ""}`,
    // React style props and chart rendering use inline style attributes, which a
    // nonce cannot cover. Scripts, the actual XSS vector, stay nonce-locked.
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data: blob:",
    "font-src 'self'",
    "connect-src 'self' https://api.pwnedpasswords.com",
    // strict-dynamic ignores 'self' for scripts, so the service worker needs its own rule.
    "worker-src 'self'",
    "manifest-src 'self'",
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "frame-ancestors 'none'",
  ].join("; ");

  const requestHeaders = new Headers(request.headers);
  requestHeaders.set("x-nonce", nonce);
  requestHeaders.set("Content-Security-Policy", policy);
  // For metadata: which page this is, and an explicit language from ?lang= (crawlable Arabic URLs).
  requestHeaders.set("x-pathname", request.nextUrl.pathname);
  const lang = request.nextUrl.searchParams.get("lang");
  if (lang === "en" || lang === "ar") requestHeaders.set("x-qalaa-lang", lang);
  else requestHeaders.delete("x-qalaa-lang");

  const response = NextResponse.next({ request: { headers: requestHeaders } });
  response.headers.set("Content-Security-Policy", policy);
  response.headers.set("X-Frame-Options", "DENY");
  return response;
}

export const config = {
  matcher: [
    {
      source: "/((?!api|_next/static|_next/image|favicon.ico|icon.svg|icons/|sw.js|manifest.webmanifest).*)",
      missing: [
        { type: "header", key: "next-router-prefetch" },
        { type: "header", key: "purpose", value: "prefetch" },
      ],
    },
  ],
};
